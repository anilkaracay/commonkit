"""Write packages/design/src/logo.ts from the approved nav lockup (concept A "Kept", D-040).

Usage: python3 export.py   (after lockup.py has written concepts/a/lockup-nav.svg)
The TS module carries the same geometry as the SVG file; src/logo.test.ts checks they stay in sync.
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
svg = (here.parent / 'concepts' / 'a' / 'lockup-nav.svg').read_text()
view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
g = re.search(r'<g fill="[^"]+" transform="([^"]+)">(.*?)</g>', svg, re.S)
rects = ''.join(r.strip() for r in re.findall(r'<rect [^>]*/>', g.group(2)))
word = re.search(r'<path fill="[^"]+" transform="([^"]+)" d="([^"]+)"', svg)
w, h = (float(v) for v in view_box.split()[2:])
ts = f'''// Generated by packages/design/logo/src/export.py from logo/concepts/a/lockup-nav.svg. Do not edit by hand.
// COMMONKIT lockup, concept A "Kept" (D-040): four identical bars keep one square, CK Sans wordmark at nav tracking.

export const LOCKUP_VIEWBOX = '{view_box}';
export const LOCKUP_ASPECT = {w / h:.5f};
export const LOCKUP_SYMBOL = '<g fill="SYMBOL" transform="{g.group(1)}">{rects}</g>';
export const LOCKUP_WORD_D = '{word.group(2)}';
const WORD_TRANSFORM = '{word.group(1)}';

/**
 * Inline SVG markup for the horizontal lockup at a given pixel height (width follows the aspect, so the
 * box is known before paint: no layout shift). The wordmark uses currentColor unless `word` is given.
 * Decorative by default: the surrounding link or heading carries the accessible name.
 */
export function lockupSvg(height: number, opts: {{ symbol?: string; word?: string; className?: string }} = {{}}): string {{
  const width = Math.round(height * LOCKUP_ASPECT * 10) / 10;
  const cls = opts.className ? ` class="${{opts.className}}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg"${{cls}} viewBox="${{LOCKUP_VIEWBOX}}" width="${{width}}" height="${{height}}" aria-hidden="true" focusable="false">${{LOCKUP_SYMBOL.replace('SYMBOL', opts.symbol ?? '#2453e0')}}<path fill="${{opts.word ?? 'currentColor'}}" transform="${{WORD_TRANSFORM}}" d="${{LOCKUP_WORD_D}}"/></svg>`;
}}
'''
(here.parents[1] / 'src' / 'logo.ts').write_text(ts)
print('wrote packages/design/src/logo.ts', len(ts), 'bytes')
