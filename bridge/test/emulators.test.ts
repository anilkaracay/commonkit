import { createHash } from "node:crypto";
import { pino } from "pino";
import { afterEach, describe, expect, it } from "vitest";
import {
  EMULATED_HEADER,
  LOADS,
  createMoonrakerEmulator,
  createOctoprintEmulator,
  createShellyGen1Emulator,
  createShellyGen2Emulator,
  createTasmotaEmulator,
  parseGcodeMeta,
  type Emulator,
} from "../src/emulators/index.js";
import { ManualClock } from "../src/util/clock.js";

const logger = pino({ level: "silent" });
const GCODE = "; generated by PrusaSlicer (demo)\n; estimated printing time (normal mode) = 20m 0s\n; filament used [mm] = 4000.0\nG28\n";
const running: Emulator[] = [];

async function serve<E extends Emulator>(e: E): Promise<E & { url: string }> {
  running.push(e);
  const url = await e.app.listen({ port: 0, host: "127.0.0.1" });
  return Object.assign(e, { url });
}
afterEach(async () => {
  for (const e of running.splice(0)) await e.app.close();
});

const upload = (url: string, path: string, fields: Record<string, string>, headers: Record<string, string> = {}) => {
  const fd = new FormData();
  for (const [k, v] of Object.entries(fields)) fd.append(k, v);
  fd.append("file", new Blob([GCODE]), "cube.gcode");
  return fetch(`${url}${path}`, { method: "POST", body: fd, headers });
};

describe("G-code metadata", () => {
  it("reads PrusaSlicer and Cura comments", () => {
    expect(parseGcodeMeta(GCODE)).toEqual({ durationSec: 1200, filamentMm: 4000 });
    expect(parseGcodeMeta(";TIME:95\n;Filament used: 1.5m\n")).toEqual({ durationSec: 95, filamentMm: 1500 });
    expect(parseGcodeMeta("; estimated printing time (normal mode) = 1h 2m 3s")).toMatchObject({ durationSec: 3723 });
  });
});

describe("Moonraker emulator (E1-E5)", () => {
  const KEY = { "x-api-key": "k123" };
  const make = async () => {
    const clock = new ManualClock();
    const e = await serve(createMoonrakerEmulator({ clock, logger, apiKey: "k123", initialTotals: { total_jobs: 12, total_filament_used: 318000 } }));
    return { e, clock };
  };
  const q = async (url: string) =>
    (await (await fetch(`${url}/printer/objects/query?print_stats&virtual_sdcard`, { headers: KEY })).json()) as {
      result: { status: { print_stats: { state: string; filament_used: number; message: string }; virtual_sdcard: { progress: number; is_active: boolean } } };
    };
  const totals = async (url: string) =>
    ((await (await fetch(`${url}/server/history/totals`, { headers: KEY })).json()) as { result: { job_totals: Record<string, number> } }).result.job_totals;

  it("requires X-Api-Key and marks every response as emulated", async () => {
    const { e } = await make();
    const res = await fetch(`${e.url}/server/history/totals`);
    expect(res.status).toBe(401);
    expect(await res.json()).toEqual({ error: { code: 401, message: "Unauthorized" } });
    expect(res.headers.get(EMULATED_HEADER)).toBe("moonraker");
  });

  it("upload+print: standby -> printing -> complete; filament grows; history totals add the job", async () => {
    const { e, clock } = await make();
    expect((await q(e.url)).result.status.print_stats.state).toBe("standby");
    const up = await upload(e.url, "/server/files/upload", { root: "gcodes", print: "true", checksum: createHash("sha256").update(GCODE).digest("hex") }, KEY);
    expect(up.status).toBe(201);
    expect(await up.json()).toMatchObject({ item: { path: "cube.gcode", root: "gcodes" }, print_started: true, action: "create_file" });
    clock.advance(600_000);
    const mid = (await q(e.url)).result.status;
    expect(mid.print_stats.state).toBe("printing");
    expect(mid.print_stats.filament_used).toBeCloseTo(2000, 0);
    expect(mid.virtual_sdcard).toMatchObject({ is_active: true, progress: 0.5 });
    clock.advance(600_001);
    expect((await q(e.url)).result.status.print_stats.state).toBe("complete");
    expect(await totals(e.url)).toMatchObject({ total_jobs: 13, total_print_time: 1200, total_filament_used: 322000 });
  });

  it("checksum mismatch -> 422; second print while busy is not started", async () => {
    const { e } = await make();
    expect((await upload(e.url, "/server/files/upload", { checksum: "0".repeat(64) }, KEY)).status).toBe(422);
    await upload(e.url, "/server/files/upload", { print: "true" }, KEY);
    expect(await (await upload(e.url, "/server/files/upload", { print: "true" }, KEY)).json()).toMatchObject({ print_started: false });
  });

  it("job_error fault: the next print errors half-way; cancel ends a print as cancelled", async () => {
    const { e, clock } = await make();
    await fetch(`${e.url}/__emulator/faults`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ job_error: true }) });
    await upload(e.url, "/server/files/upload", { print: "true" }, KEY);
    clock.advance(700_000);
    const st = (await q(e.url)).result.status.print_stats;
    expect(st.state).toBe("error");
    expect(st.message).toMatch(/emulated fault/);
    expect(await totals(e.url)).toMatchObject({ total_jobs: 13, total_print_time: 600, total_filament_used: 320000 });
    expect((await fetch(`${e.url}/printer/print/start?filename=cube.gcode`, { method: "POST", headers: KEY })).status).toBe(200);
    clock.advance(1000);
    expect((await fetch(`${e.url}/printer/print/cancel`, { method: "POST", headers: KEY })).status).toBe(200);
    expect((await q(e.url)).result.status.print_stats.state).toBe("cancelled");
  });

  it("offline fault drops connections; the control plane stays reachable", async () => {
    const { e } = await make();
    await fetch(`${e.url}/__emulator/faults`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ offline: true }) });
    await expect(fetch(`${e.url}/server/history/totals`, { headers: KEY })).rejects.toThrow();
    expect(await (await fetch(`${e.url}/__emulator`)).json()).toMatchObject({ emulated: true, simulated: true, faults: { offline: true } });
  });
});

describe("OctoPrint emulator (E6)", () => {
  it("files/local print -> Printing -> Operational; cancel -> 204; X-Api-Key required", async () => {
    const clock = new ManualClock();
    const e = await serve(createOctoprintEmulator({ clock, logger, apiKey: "ok" }));
    expect((await fetch(`${e.url}/api/job`)).status).toBe(403);
    const H = { "x-api-key": "ok" };
    const up = await upload(e.url, "/api/files/local", { select: "true", print: "true" }, H);
    expect(up.status).toBe(201);
    expect(up.headers.get("location")).toBe("/api/files/local/cube.gcode");
    const job = async () => (await (await fetch(`${e.url}/api/job`, { headers: H })).json()) as { state: string; progress: { completion: number } };
    clock.advance(300_000);
    expect(await job()).toMatchObject({ state: "Printing", progress: { completion: 25 } });
    expect((await upload(e.url, "/api/files/local", { print: "true" }, H)).status).toBe(409);
    clock.advance(900_000);
    expect((await job()).state).toBe("Operational");
    await upload(e.url, "/api/files/local", { print: "true" }, H);
    const cancel = await fetch(`${e.url}/api/job`, { method: "POST", headers: { ...H, "content-type": "application/json" }, body: JSON.stringify({ command: "cancel" }) });
    expect(cancel.status).toBe(204);
  });
});

describe("plug emulators (E7-E9)", () => {
  it("Shelly Gen2: Switch.Set / GetStatus with apower, aenergy.total (Wh), temperature; stuck fault", async () => {
    const clock = new ManualClock();
    const e = await serve(createShellyGen2Emulator({ clock, logger }));
    expect(await (await fetch(`${e.url}/rpc/Switch.Set?id=0&on=true`)).json()).toEqual({ was_on: false });
    clock.advance(3_600_000);
    const st = (await (await fetch(`${e.url}/rpc/Switch.GetStatus?id=0`)).json()) as { temperature: { tC: number; tF: number } } & Record<string, unknown>;
    expect(st).toMatchObject({ id: 0, output: true, apower: 60, voltage: 230, aenergy: { total: 60 } });
    expect(st.temperature.tC).toBeCloseTo(29.2, 1);
    expect(st.temperature.tF).toBeCloseTo(84.6, 1);
    await fetch(`${e.url}/__emulator/faults`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ stuck: true }) });
    expect(await (await fetch(`${e.url}/rpc/Switch.Set?id=0&on=false`)).json()).toEqual({ was_on: true });
    expect(((await (await fetch(`${e.url}/rpc/Switch.GetStatus?id=0`)).json()) as { output: boolean }).output).toBe(true);
  });

  it("washer_cycle load integrates exactly: 2100 W x 15 min + 350 W x 25 min + 550 W x 5 min", async () => {
    const clock = new ManualClock();
    const e = await serve(createShellyGen2Emulator({ clock, logger, load: LOADS.washer_cycle! }));
    await fetch(`${e.url}/rpc/Switch.Set?id=0&on=true`);
    clock.advance(10 * 60_000);
    expect(((await (await fetch(`${e.url}/rpc/Switch.GetStatus?id=0`)).json()) as { apower: number }).apower).toBe(2100);
    clock.advance(40 * 60_000);
    const st = (await (await fetch(`${e.url}/rpc/Switch.GetStatus?id=0`)).json()) as { apower: number; aenergy: { total: number } };
    expect(st.apower).toBe(1.5);
    expect(st.aenergy.total).toBeCloseTo(525 + 145.833 + 45.833 + 1.5 * (5 / 60), 2);
  });

  it("Shelly Gen1: /relay/0?turn, /meter/0 total in watt-minutes, basic auth", async () => {
    const clock = new ManualClock();
    const e = await serve(createShellyGen1Emulator({ clock, logger, credentials: { user: "admin", password: "pw" } }));
    expect((await fetch(`${e.url}/relay/0`)).status).toBe(401);
    const auth = { authorization: `Basic ${Buffer.from("admin:pw").toString("base64")}` };
    expect(await (await fetch(`${e.url}/relay/0?turn=on`, { headers: auth })).json()).toMatchObject({ ison: true });
    clock.advance(600_000);
    expect(await (await fetch(`${e.url}/meter/0`, { headers: auth })).json()).toMatchObject({ power: 60, total: 600 });
  });

  it("Tasmota: Power On/Off/query and Status 8 ENERGY.Total in kWh; user/password", async () => {
    const clock = new ManualClock();
    const e = await serve(createTasmotaEmulator({ clock, logger, credentials: { user: "u", password: "p" } }));
    const cm = async (c: string) => (await fetch(`${e.url}/cm?user=u&password=p&cmnd=${encodeURIComponent(c)}`)).json();
    expect((await fetch(`${e.url}/cm?cmnd=Power`)).status).toBe(401);
    expect(await cm("Power On")).toEqual({ POWER: "ON" });
    clock.advance(3_600_000);
    expect(await cm("Status 8")).toMatchObject({ StatusSNS: { ENERGY: { Total: 0.06, Power: 60, Voltage: 230 } } });
    expect(await cm("Power Off")).toEqual({ POWER: "OFF" });
    expect(await cm("Power")).toEqual({ POWER: "OFF" });
  });
});
