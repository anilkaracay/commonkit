/**
 * evidence/EVIDENCE.md — regenerated from evidence/*.json after every demo step. Superset of the
 * page `scripts/lib/evidence.ts` writes (same setup/seed/funding sections), plus per-step
 * assertions, the core-step markers, the agent limits run and pilot funding. Never edited by hand.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { EVIDENCE_DIR, explorerTx } from '../../lib/config.js';
import type { TxRecord } from '../../lib/evidence.js';
import { readSteps, type DemoStepRecord } from './record.js';

export const TOTAL_STEPS = 21;
const short = (h: string): string => `[${h.slice(0, 8)}…](${explorerTx(h)})`;
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

interface LimitsAttempt {
  id: string;
  spec: string;
  expected: string[];
  status: string;
  code: string | null;
  tx_hash: string | null;
  pass: boolean;
}
interface LimitsReport {
  generated_at: string;
  chain: string;
  all_passed: boolean;
  attempts: LimitsAttempt[];
}
interface FundingEntry {
  account_id: string;
  amount_near: string;
  tx: string;
  ok: boolean;
  at: string;
}

function readJson<T>(path: string): T | null {
  return existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as T) : null;
}

export interface EvidenceInputs {
  steps: DemoStepRecord[];
  logs: Record<string, TxRecord[]>;
  limits: LimitsReport | null;
  pilotFunding: FundingEntry[] | null;
}

/** Pure: the whole page. */
export function renderEvidence(inp: EvidenceInputs): string {
  const L: string[] = [
    '# EVIDENCE',
    '',
    'Generated by `scripts/demo/lib/evidence-md.ts` from `evidence/*.json`. Do not edit by hand. Network: NEAR **testnet**.',
    'Devices are never real hardware (D-022): steps marked *simulation* ran through the bridge against emulated devices or the simulator; the on-chain transactions are real testnet transactions.',
    '',
    '## Judge flow',
    '',
  ];
  const passed = inp.steps.filter((s) => s.status === 'passed').length;
  L.push(`${passed} of ${TOTAL_STEPS} steps passed. ★ = one of the five core steps shown in the README.`, '');
  if (inp.steps.length === 0) L.push('No judge-flow step has run yet.');
  else {
    L.push('| # | Step | Result | Transactions |', '| :--- | :--- | :--- | :--- |');
    for (const s of inp.steps) {
      const tags = [s.core ? '★' : '', s.simulated ? '(simulation)' : ''].filter(Boolean).join(' ');
      const links = s.txHashes.map(short).join(' ') || (s.no_tx_reason ? `— (${cell(s.no_tx_reason)})` : '—');
      L.push(`| ${s.step} | ${cell(s.title)} ${tags} | ${s.status === 'passed' ? '✅' : '❌'} | ${links} |`);
    }
    for (const s of inp.steps) L.push(...stepDetail(s));
  }
  if (inp.limits) L.push(...limitsSection(inp.limits));
  if (inp.pilotFunding?.length) L.push(...fundingSection(inp.pilotFunding));
  for (const [name, records] of Object.entries(inp.logs)) L.push(...logSection(name, records));
  return `${L.join('\n')}\n`;
}

function stepDetail(s: DemoStepRecord): string[] {
  const L = ['', `### Step ${s.step} — ${s.title}${s.simulated ? ' (simulation)' : ''}`, ''];
  L.push(`${s.status === 'passed' ? '✅ passed' : '❌ failed'} · ${s.timestamp.slice(0, 19).replace('T', ' ')} UTC${s.core ? ' · core step' : ''}`, '');
  if (s.error) L.push(`Error: \`${cell(s.error)}\``, '');
  for (const a of s.assertions) L.push(`- ${a.ok ? '✅' : '❌'} ${a.what}${a.detail ? ` — \`${cell(a.detail).slice(0, 300)}\`` : ''}`);
  if (s.transactions.length) {
    L.push('', '| Tx | What | By | Result |', '| :--- | :--- | :--- | :--- |');
    for (const t of s.transactions) {
      const res = t.ok ? 'ok' : t.expected_failure ? `refused as expected (${t.error_code ?? 'protocol'})` : `failed (${t.error_code ?? 'see tx'})`;
      L.push(`| ${short(t.hash)} | ${cell(t.label)} | ${t.by} | ${res} |`);
    }
  }
  for (const n of s.notes) L.push(`- Note: ${cell(n)}`);
  return L;
}

function limitsSection(r: LimitsReport): string[] {
  const L = ['', '## Agent limits (`evidence/agent-limits.json`)', ''];
  L.push(`${r.all_passed ? '✅ every limit held' : '❌ some limits not shown'} · ${r.generated_at.slice(0, 19).replace('T', ' ')} UTC · chain ${r.chain}`, '');
  L.push('| Attempt | Expected | Got | Tx |', '| :--- | :--- | :--- | :--- |');
  for (const a of r.attempts)
    L.push(`| ${a.pass ? '✅' : '❌'} ${cell(a.spec)} | ${a.expected.join(' / ')} | ${a.code ?? a.status} | ${a.tx_hash ? short(a.tx_hash) : '— (refused before execution)'} |`);
  return L;
}

function fundingSection(rows: FundingEntry[]): string[] {
  const L = ['', '## Pilot funding (`evidence/pilot-funding.json`)', '', '| When (UTC) | Account | NEAR | Tx |', '| :--- | :--- | :--- | :--- |'];
  for (const r of rows) L.push(`| ${r.at.slice(0, 19).replace('T', ' ')} | ${r.account_id} | ${r.amount_near} | ${short(r.tx)} ${r.ok ? '✅' : '❌'} |`);
  return L;
}

function logSection(name: string, records: TxRecord[]): string[] {
  const L = ['', `## ${name}`, '', '| When (UTC) | What | Tx | OK |', '| :--- | :--- | :--- | :--- |'];
  for (const r of records)
    L.push(`| ${r.at.slice(0, 19).replace('T', ' ')} | ${cell(r.label)} | [${r.hash.slice(0, 8)}…](${r.explorer}) | ${r.ok ? '✅' : '❌'} |`);
  return L;
}

export const LOG_NAMES = ['funding', 'setup', 'seed', 'demo-housekeeping'];

export function loadEvidenceInputs(dir = EVIDENCE_DIR): EvidenceInputs {
  const logs: Record<string, TxRecord[]> = {};
  for (const name of LOG_NAMES) {
    const recs = readJson<TxRecord[]>(join(dir, `${name}.json`));
    if (recs?.length) logs[name] = recs;
  }
  return {
    steps: readSteps(join(dir, 'steps.json')),
    logs,
    limits: readJson<LimitsReport>(join(dir, 'agent-limits.json')),
    pilotFunding: readJson<FundingEntry[]>(join(dir, 'pilot-funding.json')),
  };
}

export function writeEvidenceMd(dir = EVIDENCE_DIR): void {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'EVIDENCE.md'), renderEvidence(loadEvidenceInputs(dir)));
}
