/**
 * The real operations agent for demo steps: `agent/src/main.ts` on testnet (chain: near), writing
 * with its function-call key for the asset, run until the expected on-chain result appears and then
 * stopped. The demo never opens a task or an escalation for the agent: it only starts the agent.
 * Its events (with tx hashes) are read from its JSONL evidence log.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEPLOYMENTS_FILE, REPO_ROOT, RPC_URLS } from '../../lib/config.js';
import { profilePath, slugOf } from './cast.js';
import { runProc, startProc, waitFor } from './procs.js';

export const AGENT_DIR = join(REPO_ROOT, 'agent');
export const AGENT_STATE = join(AGENT_DIR, 'state', 'testnet-demo');
const AGENT_PORT = Number(process.env.DEMO_AGENT_PORT ?? 18788);

export interface AgentEvent {
  seq: number;
  at: string;
  type: string;
  asset_id: string | null;
  simulated: boolean;
  data: Record<string, unknown>;
}

export interface PurchaseHintOverride {
  rule_id: string;
  after_n: number;
  item: string;
  amount: string;
  receiver: string;
}

/** Pure: agent config for one asset (JSON is valid YAML). */
export function agentConfigText(
  assetId: string,
  o: { agent: string; rpcUrl: string; stateDir: string; evidenceDir: string; deployments: string; port: number; purchaseHints?: PurchaseHintOverride[] },
): string {
  const cfg = {
    network: 'testnet',
    agent_account: o.agent,
    chain: 'near',
    rpc_url: o.rpcUrl,
    poll_seconds: 5,
    sync_every_seconds: 30,
    listen: { host: '127.0.0.1', port: o.port },
    cors_origins: [],
    state_dir: o.stateDir,
    evidence_dir: o.evidenceDir,
    // Deterministic template rationale for the evidence (D-603); no LLM in the judge flow.
    llm: { enabled: false },
    deployments: o.deployments,
    assets: [
      {
        asset_id: assetId,
        alias: slugOf(assetId).toUpperCase().replace(/[^A-Z0-9]/g, '_'),
        profile: profilePath(slugOf(assetId)),
        simulated: true,
        supplier_is_team_account: true,
        ...(o.purchaseHints ? { purchase_hints: o.purchaseHints } : {}),
      },
    ],
  };
  return `# GENERATED by scripts/demo/lib/agent.ts for the testnet judge flow.\n${JSON.stringify(cfg, null, 2)}\n`;
}

function readEvents(dir: string): AgentEvent[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.jsonl'))
    .sort()
    .flatMap((f) => readFileSync(join(dir, f), 'utf8').split('\n').filter(Boolean))
    .map((l) => JSON.parse(l) as AgentEvent);
}

/**
 * Run the agent on one asset until `done(events)` returns a value (checked against the agent's
 * events of this run), then stop it. Throws on timeout with the agent's last skip/reject reasons.
 */
export async function runAgentUntil<T>(
  assetId: string,
  agent: string,
  tag: string,
  done: (events: AgentEvent[]) => Promise<T | null>,
  opts: { timeoutMs?: number; purchaseHints?: PurchaseHintOverride[] } = {},
): Promise<{ result: T; events: AgentEvent[] }> {
  const evidenceDir = join(AGENT_STATE, 'runs', `${tag}-${Date.now()}`);
  mkdirSync(evidenceDir, { recursive: true });
  const cfgPath = join(evidenceDir, 'agent.yaml');
  writeFileSync(
    cfgPath,
    agentConfigText(assetId, {
      agent,
      rpcUrl: RPC_URLS[0]!,
      stateDir: AGENT_STATE,
      evidenceDir,
      deployments: DEPLOYMENTS_FILE,
      port: AGENT_PORT,
      ...(opts.purchaseHints ? { purchaseHints: opts.purchaseHints } : {}),
    }),
  );
  const proc = startProc(join(AGENT_DIR, 'node_modules', '.bin', 'tsx'), ['src/main.ts', '--config', cfgPath], {
    cwd: AGENT_DIR,
    env: { NEAR_RPC_URL: RPC_URLS[0]! },
    logFile: join(evidenceDir, 'agent.log'),
  });
  console.log(`  agent started on ${slugOf(assetId)} (log ${proc.logFile})`);
  try {
    const result = await waitFor(`the agent on ${slugOf(assetId)}`, async () => {
      if (proc.child.exitCode !== null) throw new Error(`agent exited (${proc.child.exitCode}); see ${proc.logFile}`);
      return done(readEvents(evidenceDir));
    }, opts.timeoutMs ?? 180_000, 3000).catch((e: unknown) => {
      const why = readEvents(evidenceDir)
        .filter((x) => /agent_waiting|write_rejected|write_failed|agent_error|signer_status/.test(x.type))
        .slice(-4)
        .map((x) => `${x.type} ${JSON.stringify(x.data)}`)
        .join('; ');
      throw new Error(`${(e as Error).message}${why ? ` — agent said: ${why}` : ''}`);
    });
    return { result, events: readEvents(evidenceDir) };
  } finally {
    await proc.stop();
  }
}

/** DEMO_SCRIPT step 16: the agent's own limits demo against testnet (writes evidence/agent-limits.json). */
export async function runLimitsDemo(revokedAsset: string, quotaAsset: string): Promise<{ code: number | null; out: string; reportPath: string }> {
  const r = await runProc(
    join(AGENT_DIR, 'node_modules', '.bin', 'tsx'),
    ['src/limits-demo.ts', '--chain', 'near', '--send-testnet-transactions', '--revoked-asset', revokedAsset, '--quota-asset', quotaAsset, '--rpc', RPC_URLS[0]!],
    { cwd: AGENT_DIR, env: { NEAR_RPC_URL: RPC_URLS[0]! } },
  );
  return { ...r, reportPath: join(REPO_ROOT, 'evidence', 'agent-limits.json') };
}
