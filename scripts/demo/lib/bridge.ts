/**
 * The real bridge for device steps (D-022): `bridge/src/emulated-stack.ts` started as a child
 * process with `chain: near`, writing with the bridge's function-call keys. The printer goes
 * through the moonraker adapter to the emulated Moonraker, the laser through smart_plug to the
 * emulated Shelly (lamp-class stand-in), washer and fridge through the simulator. Everything it
 * does is SIMULATED / emulated device, and the demo steps say so.
 *
 * Members sign bridge requests with NEP-413 using their own full-access keychain key (D-019).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEPLOYMENTS_FILE, REPO_ROOT, RPC_URLS } from '../../lib/config.js';
import { keychainNep413Signer, type Nep413Payload } from './nep413.js';
import { sleep, startProc, waitFor, type Proc } from './procs.js';

export const BRIDGE_DIR = join(REPO_ROOT, 'bridge');
export const BRIDGE_STATE = join(BRIDGE_DIR, 'state', 'testnet-demo');
export const BRIDGE_PORT = Number(process.env.DEMO_BRIDGE_PORT ?? 18787);

export type DeviceKind = 'printer' | 'laser' | 'washer' | 'fridge';

export interface BridgeAssets {
  printer?: string;
  laser?: string;
  washer?: string;
  fridge?: string;
}

/**
 * Pure: bridge config for the given assets (same adapters and settings as bridge/config.emulated.yaml,
 * absolute paths, own state dir). JSON is valid YAML; `${EMU_*}` are filled in by the emulated stack.
 */
export function bridgeConfigText(
  assets: BridgeAssets,
  o: { port: number; rpcUrl: string; bridgeAccount: string; stateDir: string; deployments: string; bridgeDir: string },
): string {
  const list: object[] = [];
  const g = (p: string) => join(o.bridgeDir, p);
  if (assets.printer)
    list.push({
      asset_id: assets.printer,
      adapter: 'moonraker',
      emulated_device: true,
      adapter_config: {
        base_url: '${EMU_MOONRAKER_URL}',
        api_key_env: 'EMU_MOONRAKER_API_KEY',
        default_job: g('gcode/demo_cube.gcode'),
        time_scale: '__EMU_SPEED__',
        poll_ms: 1000,
      },
      telemetry_interval_sec: 10,
      session_timeout_min: 240,
      session_poll_sec: 1,
      verification_tests: Object.fromEntries(
        ['nozzle_clean', 'bed_level', 'fault_repair'].map((r) => [r, { type: 'calibration_print', file: g('gcode/calibration_cube.gcode'), max_minutes: 15 }]),
      ),
    });
  if (assets.laser)
    list.push({
      asset_id: assets.laser,
      adapter: 'smart_plug',
      emulated_device: true,
      adapter_config: {
        vendor: 'shelly_gen2',
        base_url: '${EMU_SHELLY_URL}',
        session_end: 'manual',
        active_watts_threshold: 20,
        time_scale: '__EMU_SPEED__',
        poll_ms: 2000,
        report_temperature: true,
      },
      safety: {
        dangerous: true,
        stand_in: 'emulated 60 W lamp-class load (stand-in for the laser cutter; nothing is energised)',
      },
      telemetry_interval_sec: 10,
      session_timeout_min: 60,
      session_poll_sec: 1,
      gauges: { temperature_c: [{ derive: 'samples_above', limit: 45, counter: 'plug_hot_samples' }] },
      verification_tests: Object.fromEntries(
        ['lens_clean', 'monthly_safety_check'].map((r) => [r, { type: 'power_profile', expect: { min_watts: 40, max_watts: 80, seconds: 60 } }]),
      ),
    });
  if (assets.washer)
    list.push({
      asset_id: assets.washer,
      adapter: 'simulator',
      adapter_config: { scenario: g('test/fixtures/scenarios/washer.yaml') },
      telemetry_interval_sec: 5,
      session_timeout_min: 120,
    });
  if (assets.fridge)
    list.push({
      asset_id: assets.fridge,
      adapter: 'simulator',
      adapter_config: { scenario: g('test/fixtures/scenarios/community_fridge.yaml') },
      telemetry_interval_sec: 10,
      session_timeout_min: 10,
      gauges: { temperature_c: [{ derive: 'samples_above', limit: 8, counter: 'temp_high_samples' }] },
    });
  if (list.length === 0) throw new Error('bridge needs at least one asset');
  const cfg = {
    network: 'testnet',
    rpc_url: o.rpcUrl,
    bridge_account: o.bridgeAccount,
    chain: 'near',
    listen: { host: '127.0.0.1', port: o.port },
    state_dir: o.stateDir,
    evidence_dir: join(o.stateDir, 'evidence'),
    cors_origins: [],
    signer: { deployments: o.deployments },
    assets: list,
  };
  const header = '# GENERATED by scripts/demo/lib/bridge.ts for the testnet judge flow. SIMULATED assets, emulated devices.\n';
  return header + JSON.stringify(cfg, null, 2).replace(/"__EMU_SPEED__"/g, '${EMU_SPEED:-60}') + '\n';
}

export interface Challenge {
  nonce: string;
  message: string;
  recipient: string;
}

export interface HttpResult<T = Record<string, unknown>> {
  status: number;
  body: T;
}

type Sign = (p: Nep413Payload) => { publicKey: string; signature: string };

/** HTTP client playing the member's app + wallet against the bridge. */
export class BridgeClient {
  private readonly signers = new Map<string, Sign>();
  constructor(
    readonly baseUrl: string,
    private readonly signerFor: (account: string) => Sign = keychainNep413Signer,
  ) {}

  private sign(account: string): Sign {
    let s = this.signers.get(account);
    if (!s) this.signers.set(account, (s = this.signerFor(account)));
    return s;
  }

  async request<T = Record<string, unknown>>(method: 'GET' | 'POST', path: string, body?: unknown): Promise<HttpResult<T>> {
    const res = await fetch(`${this.baseUrl}${path}`, {
      method,
      headers: body === undefined ? {} : { 'content-type': 'application/json' },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    const text = await res.text();
    let parsed: unknown;
    try {
      parsed = JSON.parse(text);
    } catch {
      parsed = { raw: text };
    }
    return { status: res.status, body: parsed as T };
  }

  /** challenge → NEP-413 signature with the account's key → signed POST to `path`. */
  async signed(
    path: string,
    req: { asset_id: string; account_id: string; action: 'access' | 'finish' | 'verify' | 'confirm'; reservation_id?: string; task_id?: string },
    extra: Record<string, unknown> = {},
  ): Promise<HttpResult> {
    const ch = await this.request<Challenge>('POST', '/access/challenge', req);
    if (ch.status !== 200) return ch as unknown as HttpResult;
    const c = ch.body;
    const { publicKey, signature } = this.sign(req.account_id)({
      message: c.message,
      nonce: Buffer.from(c.nonce, 'base64'),
      recipient: c.recipient,
      callbackUrl: null,
    });
    const { action: _a, ...rest } = req;
    return this.request('POST', path, { ...rest, ...extra, public_key: publicKey, signature, nonce: c.nonce, message: c.message, recipient: c.recipient });
  }

  access(asset: string, account: string, reservationId: string) {
    return this.signed('/access', { asset_id: asset, account_id: account, action: 'access', reservation_id: reservationId });
  }
  finish(sessionId: string, asset: string, account: string, reservationId: string) {
    return this.signed(`/sessions/${sessionId}/finish`, { asset_id: asset, account_id: account, action: 'finish', reservation_id: reservationId });
  }
  verify(asset: string, taskId: string, account: string) {
    return this.signed(`/verification/${asset}/${taskId}/run`, { asset_id: asset, account_id: account, action: 'verify', task_id: taskId });
  }
  session(id: string) {
    return this.request<BridgeSession>('GET', `/sessions/${id}`);
  }
  run(id: string) {
    return this.request<VerificationRun>('GET', `/verification/runs/${id}`);
  }
  async device(asset: string): Promise<Record<string, unknown> | null> {
    const r = await this.request<{ asset_id: string; status: { details?: Record<string, unknown> } }[]>('GET', '/assets');
    return r.body.find((a) => a.asset_id === asset)?.status?.details ?? null;
  }

  /** Wait until the session reaches `finished` (or another end state); returns it. */
  waitSessionEnd(id: string, timeoutMs: number): Promise<BridgeSession> {
    return waitFor(`bridge session ${id} to finish`, async () => {
      const s = (await this.session(id)).body;
      return s.status === 'finished' && s.finish_tx ? s : null;
    }, timeoutMs, 2000);
  }

  waitRun(id: string, timeoutMs: number): Promise<VerificationRun> {
    return waitFor(`verification run ${id}`, async () => {
      const r = (await this.run(id)).body;
      if (r.status === 'failed') throw new Error(`verification run failed: ${r.error}`);
      return r.tx ? r : null;
    }, timeoutMs, 2000);
  }
}

export interface BridgeSession {
  session_id: string;
  status: string;
  finish_reason: string | null;
  start_tx: string | null;
  finish_tx: string | null;
  metrics_at_end: Record<string, string> | null;
  simulated: boolean;
}

export interface VerificationRun {
  run_id: string;
  status: string;
  passed: boolean | null;
  details_hash: string | null;
  tx: string | null;
  error: string | null;
  test: unknown;
  simulated: boolean;
}

/** Start the emulated stack on testnet for `assets`; returns the client and a stop handle. */
export async function startBridge(assets: BridgeAssets, bridgeAccount: string, tag: string): Promise<{ client: BridgeClient; proc: Proc }> {
  mkdirSync(BRIDGE_STATE, { recursive: true });
  const cfgPath = join(BRIDGE_STATE, `bridge.${tag}.yaml`);
  writeFileSync(
    cfgPath,
    bridgeConfigText(assets, {
      port: BRIDGE_PORT,
      rpcUrl: RPC_URLS[0]!,
      bridgeAccount,
      stateDir: BRIDGE_STATE,
      deployments: DEPLOYMENTS_FILE,
      bridgeDir: BRIDGE_DIR,
    }),
  );
  const proc = startProc(join(BRIDGE_DIR, 'node_modules', '.bin', 'tsx'), ['src/emulated-stack.ts', '--config', cfgPath, '--speed', '60'], {
    cwd: BRIDGE_DIR,
    env: { NEAR_RPC_URL: RPC_URLS[0]! },
    logFile: join(BRIDGE_STATE, 'logs', `bridge-${tag}-${Date.now()}.log`),
  });
  const client = new BridgeClient(`http://127.0.0.1:${BRIDGE_PORT}`);
  try {
    await waitFor('bridge /health', async () => {
      if (proc.child.exitCode !== null) throw new Error(`bridge exited (${proc.child.exitCode}); see ${proc.logFile}`);
      const h = await client.request<{ ok: boolean; chain: string }>('GET', '/health');
      return h.status === 200 && h.body.chain === 'near' ? h : null;
    }, 90_000, 1000);
  } catch (e) {
    await proc.stop();
    throw e;
  }
  console.log(`  bridge up (chain near, SIMULATED devices) on ${client.baseUrl}; log ${proc.logFile}`);
  await sleep(1500);
  return { client, proc };
}
