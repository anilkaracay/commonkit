/**
 * Evidence log. Setup/seed transactions go to `evidence/<log>.json` (append-only arrays);
 * judge-flow steps go to `evidence/steps.json` and `evidence/EVIDENCE.md` is regenerated from
 * all of them (TEST_PLAN §5).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { EVIDENCE_DIR, explorerTx } from './config.js';
import type { TxResult } from './near.js';

export interface TxRecord {
  at: string;
  label: string;
  hash: string;
  signer: string;
  receiver: string;
  ok: boolean;
  explorer: string;
  events: string[];
  failure?: string;
  receipt_failures?: string[];
}

export interface StepRecord {
  step: number;
  title: string;
  txHashes: string[];
  explorerLinks: string[];
  assertions: { what: string; ok: boolean; detail?: string }[];
  timestamp: string;
  simulated?: boolean;
}

export function toRecord(label: string, tx: TxResult, now = new Date()): TxRecord {
  return {
    at: now.toISOString(),
    label,
    hash: tx.hash,
    signer: tx.signer,
    receiver: tx.receiver,
    ok: tx.ok,
    explorer: explorerTx(tx.hash),
    events: tx.events.map((e) => `${e.standard}:${e.event}`),
    ...(tx.failure ? { failure: tx.failure } : {}),
    ...(tx.receiptFailures.length ? { receipt_failures: tx.receiptFailures } : {}),
  };
}

function readArray<T>(path: string): T[] {
  return existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as T[]) : [];
}

function writeJson(path: string, value: unknown): void {
  mkdirSync(EVIDENCE_DIR, { recursive: true });
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
}

export class EvidenceLog {
  readonly path: string;
  constructor(
    readonly name: string,
    readonly dir = EVIDENCE_DIR,
  ) {
    this.path = join(dir, `${name}.json`);
  }

  /** Append tx records and print one line per tx (hash + label, never keys). */
  add(label: string, ...txs: TxResult[]): void {
    const all = readArray<TxRecord>(this.path);
    for (const tx of txs) {
      all.push(toRecord(label, tx));
      console.log(`  ${tx.ok ? 'tx' : 'tx FAILED'} ${tx.hash}  ${label}`);
    }
    writeJson(this.path, all);
    renderEvidenceMd(this.dir);
  }

  records(): TxRecord[] {
    return readArray<TxRecord>(this.path);
  }
}

/** Upsert a judge-flow step record (one record per step number; reruns replace it). */
export function appendStep(record: StepRecord, dir = EVIDENCE_DIR): void {
  const path = join(dir, 'steps.json');
  const steps = readArray<StepRecord>(path).filter((s) => s.step !== record.step);
  steps.push(record);
  steps.sort((a, b) => a.step - b.step);
  writeJson(path, steps);
  renderEvidenceMd(dir);
}

/** Pure: Markdown for EVIDENCE.md from step records and setup/seed logs. */
export function evidenceMarkdown(steps: StepRecord[], logs: Record<string, TxRecord[]>): string {
  const lines = [
    '# EVIDENCE',
    '',
    'Generated by `scripts/lib/evidence.ts` from `evidence/*.json`. Do not edit by hand. Network: NEAR **testnet**.',
    '',
    '## Judge flow',
    '',
  ];
  if (steps.length === 0) lines.push('No judge-flow step has run yet.');
  else {
    lines.push('| # | Step | Result | Transactions |', '| :--- | :--- | :--- | :--- |');
    for (const s of steps) {
      const ok = s.assertions.every((a) => a.ok);
      const links = s.txHashes.map((h) => `[${h.slice(0, 8)}…](${explorerTx(h)})`).join(' ');
      lines.push(
        `| ${s.step} | ${s.title}${s.simulated ? ' (simulation)' : ''} | ${ok ? '✅' : '❌'} | ${links || '—'} |`,
      );
    }
  }
  for (const [name, records] of Object.entries(logs)) {
    lines.push(
      '',
      `## ${name}`,
      '',
      '| When (UTC) | What | Tx | OK |',
      '| :--- | :--- | :--- | :--- |',
    );
    for (const r of records)
      lines.push(
        `| ${r.at.slice(0, 19).replace('T', ' ')} | ${r.label} | [${r.hash.slice(0, 8)}…](${r.explorer}) | ${r.ok ? '✅' : '❌'} |`,
      );
  }
  return `${lines.join('\n')}\n`;
}

export function renderEvidenceMd(dir = EVIDENCE_DIR): void {
  const steps = readArray<StepRecord>(join(dir, 'steps.json'));
  const logs: Record<string, TxRecord[]> = {};
  for (const name of ['funding', 'setup', 'seed']) {
    const recs = readArray<TxRecord>(join(dir, `${name}.json`));
    if (recs.length) logs[name] = recs;
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'EVIDENCE.md'), evidenceMarkdown(steps, logs));
}
